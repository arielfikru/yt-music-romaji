// Builds src/kanji-readings.js from Unicode's Unihan_Readings.txt (kJapanese field: on'yomi in
// katakana, kun'yomi in hiragana). Used as a last resort for kanji the dictionary doesn't know.
// Usage: node dev/build-kanji.mjs path/to/Unihan_Readings.txt
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(process.argv[2], "utf8");
const table = {};
for (const line of src.split("\n")) {
  const m = /^U\+([0-9A-F]+)\tkJapanese\t(.+)$/.exec(line);
  if (!m) continue;
  const cp = parseInt(m[1], 16);
  // Main CJK block + compatibility ideographs; the extension blocks are rare in Japanese text.
  if (!((cp >= 0x4e00 && cp <= 0x9fff) || (cp >= 0xf900 && cp <= 0xfaff))) continue;
  const readings = m[2].split(" ");
  const on = readings.find((r) => /^[゠-ヿ]+$/.test(r)) ?? "";
  const kun = readings.find((r) => /^[぀-ゟ]+$/.test(r)) ?? "";
  if (on || kun) table[String.fromCodePoint(cp)] = on + "|" + kun;
}
writeFileSync(
  "src/kanji-readings.js",
  "// Generated by dev/build-kanji.mjs from Unicode Unihan (kJapanese). Format: kanji -> \"ON|kun\".\n" +
    "export default " + JSON.stringify(table) + ";\n"
);
console.log(Object.keys(table).length, "kanji");
